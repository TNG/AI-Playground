export const DRIVER_CHANNELS: ReadonlySet<string> = new Set<InvokeChannelName>([
  'chat:submitTurn',
  'chat:resumeTurn',
  'agentMode:startTurn',
  'artifact:run',
  'sessions:beginTurn',
])

export function ipcRoute(channel: string): IpcRoute | undefined {
  return (
    (INVOKE_ROUTES as Record<string, IpcRoute>)[channel] ??
    (SEND_ROUTES as Record<string, IpcRoute>)[channel]
  )
}

export function pushRoute(channel: string): PushRoute {
  return (PUSH_ROUTES as Record<string, PushRoute>)[channel] ?? 'local'
}
