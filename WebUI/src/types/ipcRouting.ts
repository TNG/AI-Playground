import type { InvokeChannelName, PushChannelName, SendChannelName } from './ipcChannels'

/**
 * Where a channel runs when this app is a remote-kernel thin client. `remote` rows are
 * forwarded to the workstation and are the only ones its host will dispatch; `local`
 * rows stay on the client (window chrome, native dialogs, this device's own state).
 */
export type IpcRoute = 'local' | 'remote'

/**
 * Who receives a main → renderer push while remote clients are connected: `broadcast`
 * reaches every window, `driver` only the renderer that last started a turn or run (a
 * push that makes the renderer execute work must not run twice), `local` this window.
 */
export type PushRoute = 'local' | 'broadcast' | 'driver'

